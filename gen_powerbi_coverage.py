#!/usr/bin/env python3
"""Generate POWERBI.md's coverage block from the database instead of by hand (P13).

The doc quoted 19,250 reviews and 4,423 cells long after the corpus had grown to
22,228 / 5,190 — a hand-written number in a document that tells an outside team
what they will see is a number that will be wrong. Every figure below is a live
query, and cx_refresh.sh re-runs this so the block cannot drift again.

It also measures the duplicate grain rather than describing it vaguely: the same
review text appears on several review_ids (cross-marketplace copies), so SKU×month
counts overstate distinct customer complaints. The flag now lives in the view
(dup_rank/dup_group: same MD5(text), SKU and review_date, prose rows only), so this
block and the app's footer measure the same thing; nothing is deduped, and the
caveat states the measured size and tells the reader to label n as "reviews".

Idempotent: rewrites only the text between the coverage markers, byte-identical when
the numbers have not moved.

  --check   exit 1 if the block on disk differs from what the database says
            (so a stale doc is a failed step, not a surprise in a meeting)
"""
import argparse
import os
import sys

import pymysql

HERE = os.path.dirname(os.path.abspath(__file__))
DOC = os.path.join(HERE, "POWERBI.md")
START = "<!-- coverage:start -->"
END = "<!-- coverage:end -->"
# The denominator block. Same idea: every figure a live query, so the doc cannot
# claim a coverage number the database stopped supporting. Added 2026-10-19 with
# sales_by_sku_month / v_complaint_rates.
S_START = "<!-- sales:start -->"
S_END = "<!-- sales:end -->"


def db():
    return pymysql.connect(
        host=os.environ["CXAPP_DB_HOST"], user=os.environ["CXAPP_DB_USER"],
        password=os.environ["CXAPP_DB_PASSWORD"], database=os.environ["CXAPP_DB_NAME"],
        charset="utf8mb4")


def one(cur, sql, args=()):
    cur.execute(sql, args)
    return cur.fetchone()


def facts():
    conn = db()
    cur = conn.cursor()
    f = {}
    f["rows"] = one(cur, "SELECT COUNT(*) FROM classifications")[0]
    f["validated"] = one(cur, """SELECT COUNT(*) FROM v_ai_complaints
                                  WHERE human_validated=1""")[0]
    f["since_jun"] = one(cur, "SELECT COUNT(*) FROM classifications "
                              "WHERE review_date >= '2026-06-01'")[0]
    f["min_d"], f["max_d"] = one(cur, "SELECT MIN(review_date), MAX(review_date) "
                                      "FROM classifications")
    f["cells"] = one(cur, "SELECT COUNT(*) FROM v_ai_complaints_monthly")[0]
    f["cells_n"] = one(cur, "SELECT COALESCE(SUM(n),0) FROM v_ai_complaints_monthly")[0]
    f["single"] = one(cur, "SELECT COUNT(*) FROM v_ai_complaints_monthly WHERE n=1")[0]
    f["no_month"] = f["rows"] - f["cells_n"]
    f["corrections"] = one(cur, "SELECT COUNT(*) FROM corrections")[0]
    # Repeat grain: straight off the tables the views join, so this block cannot
    # disagree with the app's footer. Keyed on order_id + MD5(text) with a
    # SKU/date fallback for the rows that carry no order (F2).
    f["dup_groups"], f["dup_rows"], f["dup_extra"] = one(cur, """
        SELECT COUNT(*), COALESCE(SUM(n),0), COALESCE(SUM(n-1),0)
          FROM review_duplicates""")
    f["dup_groups"], f["dup_rows"], f["dup_extra"] = (
        int(f["dup_groups"]), int(f["dup_rows"]), int(f["dup_extra"]))
    f["dup_share"] = 100.0 * f["dup_extra"] / max(f["rows"], 1)
    # Process noise, a DIFFERENT number from the repeats: 351 rows the rule
    # removed. It must never share the word "duplicate" with the repeats above.
    f["noise"] = one(cur, "SELECT COUNT(*) FROM v_rule_deletions")[0]
    conn.close()
    return f


def block(f):
    rows = f["rows"]
    return "\n".join([
        START,
        f"<!-- generated by gen_powerbi_coverage.py from automation_philip; do not edit by hand -->",
        "",
        "### Coverage (live, read from the database)",
        "",
        "| fact | value |",
        "|---|---|",
        f"| classified complaint records | **{rows:,}** |",
        f"| human-validated (`human_validated=1`) | **{f['validated']:,}** "
        f"({100.0 * f['validated'] / max(rows, 1):.1f}% of the corpus) |",
        f"| decisions recorded (app + sheet) | {f['corrections']:,} |",
        f"| record dates | {f['min_d']} → {f['max_d']} |",
        f"| records dated Jun 2026 or later | {f['since_jun']:,} "
        f"({100.0 * f['since_jun'] / max(rows, 1):.1f}%) |",
        f"| SKU × month × complaint cells in `v_ai_complaints_monthly` | **{f['cells']:,}** |",
        f"| of those, cells holding exactly one record | {f['single']:,} "
        f"({100.0 * f['single'] / max(f['cells'], 1):.1f}%) |",
        f"| rows not counted in `v_ai_complaints_monthly` | {f['no_month']:,} "
        f"(no complaint/date/SKU, or excluded by the view; `{rows:,}` − "
        f"`{f['cells_n']:,}` counted) |",
        "",
        "### Repeat grain — read this before quoting a total",
        "",
        f"The same comment is recorded more than once on the same ORDER "
        f"(`order_id` + MD5(text)): {f['dup_groups']:,} groups covering "
        f"{f['dup_rows']:,} rows, so {f['dup_extra']:,} rows "
        f"({f['dup_share']:.1f}% of the corpus) repeat a comment already recorded on "
        f"that order. Nothing is deduped — every count above is every row.",
        "",
        "The flag rides in the views as `dup_rank` / `dup_group` (rank 1 is the first "
        "row of its group, rank 2 repeats one; the ~40 rows with no `order_id` fall "
        "back to SKU + date + MD5). So:",
        "",
        "- label `n` as **complaint records**, never \"customers\" or \"complaints "
        "received\";",
        "- treat absolute totals as an upper bound; shares (%) are much less affected "
        "because the repeats carry the same labels;",
        "- for distinct complaints, filter `dup_rank = 1` (the app's 'distinct "
        "complaints' toggle does the same: `dup=1`), and say so on the page — "
        "21,000 rows and 20,000 rows are different denominators, not a restatement.",
        "",
        f"Separately, **{f['noise']:,} rows are process noise** (`Review Deletion`: "
        "empty or non-complaint text removed by the rule). They are excluded from "
        "every distribution and are a different thing from the repeats above — do "
        "not describe them as duplicates.",
        "",
        "Any trend before June 2026 rests on very few rows — filter `month >= '2026-06'` "
        "in any visual that claims a trend.",
        END,
    ])


def read_doc():
    try:
        return open(DOC, encoding="utf-8").read()
    except OSError:
        return ""


def sales_facts():
    """The denominator's coverage, measured — not the number typed into the prose."""
    conn = db()
    cur = conn.cursor()
    s = {}
    cur.execute(f"""SELECT COUNT(*) rows_n, COUNT(DISTINCT sku) skus,
                           MIN(month) mn, MAX(month) mx, SUM(orders) orders,
                           SUM(units) units, SUM(refunds) refunds,
                           SUM(orders = 0) zero_orders
                      FROM sales_by_sku_month""")
    (s["rows"], s["skus"], s["mn"], s["mx"], s["orders"], s["units"],
     s["refunds"], s["zero_orders"]) = cur.fetchone()
    cur.execute("""SELECT COUNT(*) rows_n, SUM(has_sales = 1) covered,
                          SUM(has_sales = 0) no_sales, SUM(orders = 0) zero_order_rows
                     FROM v_complaint_rates""")
    (s["v_rows"], s["v_covered"], s["v_no_sales"], s["v_zero"]) = cur.fetchone()
    cur.execute("""SELECT SUM(s.sku IS NOT NULL) cov_pairs, COUNT(*) pairs,
                          SUM(CASE WHEN s.sku IS NOT NULL THEN x.n ELSE 0 END) cov_recs,
                          SUM(x.n) recs
                     FROM (SELECT sku, month, SUM(n_complaints) n FROM v_complaint_rates
                            WHERE sku IS NOT NULL AND month IS NOT NULL
                            GROUP BY sku, month) x
                     LEFT JOIN sales_by_sku_month s
                            ON s.sku = x.sku AND s.month = x.month""")
    (s["cov_pairs"], s["pairs"], s["cov_recs"], s["recs"]) = cur.fetchone()
    conn.close()
    # COUNT/SUM come back as int/Decimal depending on the driver; the block only
    # formats numbers, so make every count an int and leave mn/mx as strings.
    out = {}
    for k, v in s.items():
        out[k] = v if k in ("mn", "mx") else int(v or 0)
    return out


def sales_block(f):
    pct_pairs = 100.0 * f["cov_pairs"] / max(f["pairs"], 1)
    pct_recs = 100.0 * f["cov_recs"] / max(f["recs"], 1)
    return "\n".join([
        S_START,
        "<!-- generated by gen_powerbi_coverage.py from automation_philip; do not edit by hand -->",
        "",
        "### Sales denominator (live, read from the database)",
        "",
        "| fact | value |",
        "|---|---|",
        f"| `sales_by_sku_month` rows (SKU × month) | **{f['rows']:,}** |",
        f"| seller SKUs with sales | {f['skus']:,} |",
        f"| finance months covered | {f['mn']} → {f['mx']} |",
        f"| orders / units / refunds in the table | {f['orders']:,} / {f['units']:,} / {f['refunds']:,} |",
        f"| SKU-months with finance rows but 0 orders | {f['zero_orders']:,} (the rate is NULL there) |",
        f"| `v_complaint_rates` rows | {f['v_rows']:,} |",
        f"| of those, with a sales denominator | {f['v_covered']:,} "
        f"({100.0 * f['v_covered'] / max(f['v_rows'], 1):.1f}%) |",
        f"| with no sales row (rate NULL) | {f['v_no_sales']:,} |",
        f"| with 0 orders (rate NULL) | {f['v_zero']:,} |",
        f"| complaint SKU-months covered | {f['cov_pairs']:,}/{f['pairs']:,} ({pct_pairs:.2f}%) |",
        f"| complaint records covered | {f['cov_recs']:,}/{f['recs']:,} ({pct_recs:.2f}%) |",
        "",
        f"A rate quoted from `v_complaint_rates` covers **{pct_recs:.2f}% of the complaint "
        f"corpus**. The remaining {f['recs'] - f['cov_recs']:,} records sit in "
        f"{f['pairs'] - f['cov_pairs']:,} SKU-months with no finance row; their rate is NULL "
        "and must be shown as blank, never 0.",
        S_END,
    ])


def replace_block(doc, start, end, block):
    if start in doc and end in doc:
        head, rest = doc.split(start, 1)
        _, tail = rest.split(end, 1)
        return head + block + tail
    return doc.rstrip() + "\n\n" + block + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true",
                    help="exit 1 when the block on disk is stale (no write)")
    a = ap.parse_args()

    f = facts()
    new_block = block(f)
    sf = sales_facts()
    doc = read_doc()
    updated = replace_block(doc, START, END, new_block)
    updated = replace_block(updated, S_START, S_END, sales_block(sf))

    if a.check:
        if updated.strip() != doc.strip():
            print("STALE: POWERBI.md coverage block differs from the database",
                  file=sys.stderr)
            return 1
        print(f"POWERBI.md coverage block is current ({f['rows']:,} rows, "
              f"{f['cells']:,} cells, {sf['rows']:,} sku-months)")
        return 0

    if updated == doc:
        print(f"POWERBI.md coverage block unchanged ({f['rows']:,} rows, "
              f"{f['cells']:,} cells, {f['validated']:,} validated, "
              f"{f['dup_extra']:,} duplicate rows)")
        return 0
    with open(DOC, "w", encoding="utf-8") as fh:
        fh.write(updated)
    print(f"POWERBI.md coverage block updated: {f['rows']:,} rows, {f['cells']:,} cells, "
          f"{f['single']:,} single-review cells, {f['validated']:,} validated, "
          f"{f['dup_extra']:,} duplicate rows ({f['dup_share']:.1f}%)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
